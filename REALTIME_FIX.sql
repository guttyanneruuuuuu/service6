-- ============================================================
-- Supabase Realtime 権限設定の修正
-- ============================================================
-- 
-- 問題: RLSが有効なテーブルでは、Realtimeが権限を確認するため、
-- 匿名ユーザーが変更通知を受け取れない場合がある。
--
-- 解決: Realtime用の特別なロール（anon）に対して、
-- pinsテーブルの SELECT 権限を明示的に付与する。
-- ============================================================

-- 1. anon ロールに対して pins テーブルの SELECT 権限を付与
GRANT SELECT ON public.pins TO anon;

-- 2. Realtime用の特別なポリシーを追加
-- （既存のポリシーに加えて、Realtime購読用のポリシー）
CREATE POLICY "Allow realtime for anon" ON public.pins
  FOR SELECT
  TO anon
  USING (true);

-- 3. 確認: 以下のコマンドで権限が付与されているか確認
-- \dp public.pins

